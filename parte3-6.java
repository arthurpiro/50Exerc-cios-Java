public class exercicio6 {
    public static void main(String[] args) {

        int cont = 1;

        while (cont <= 20) {
            System.out.println(cont);
            cont = cont + 1;
        }

        cont = 1;
        while (cont <= 20) {
            System.out.print(cont + " ");
            cont = cont + 1;
        }
    }
}
